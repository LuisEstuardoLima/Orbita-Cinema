-- Órbita Cinema: tablas para reservas, detalle, pagos, boletos y lealtad
-- Compatible con las tablas existentes en public:
-- usuarios(id_usuario uuid), funcion(id bigint), asiento(id bigint)
--
-- IMPORTANTE:
-- 1) Ejecutar una sola vez en Supabase SQL Editor, después de revisar este archivo.
-- 2) Este script crea el esquema de datos y activa RLS. No implementa por sí solo
--    el flujo transaccional de compra ni la liberación automática de bloqueos.
-- 3) Las escrituras críticas deben hacerse desde backend seguro / RPC autorizado,
--    nunca exponiendo SUPABASE_SERVICE_ROLE_KEY al navegador.

BEGIN;

-- 1. RESERVA: incluye el checkout pendiente y su bloqueo temporal de 5 minutos.
CREATE TABLE public.reserva (
    id_reserva              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario              uuid NULL
        REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    id_funcion              bigint NOT NULL
        REFERENCES public.funcion(id) ON DELETE RESTRICT,

    -- Copia de los datos del comprador al momento de comprar (también para invitados).
    nombre_comprador        text NOT NULL
        CHECK (length(btrim(nombre_comprador)) > 0),
    correo_comprador        text NOT NULL
        CHECK (length(btrim(correo_comprador)) > 0),
    telefono_comprador      text NULL,

    fecha_reserva           timestamptz NOT NULL DEFAULT now(),
    fecha_bloqueo           timestamptz NOT NULL DEFAULT now(),
    fecha_expiracion        timestamptz NOT NULL DEFAULT (now() + interval '5 minutes'),

    subtotal                numeric(10,2) NOT NULL CHECK (subtotal >= 0),
    porcentaje_recargo     numeric(5,2) NOT NULL DEFAULT 5.00
        CHECK (porcentaje_recargo >= 0 AND porcentaje_recargo <= 100),
    recargo                 numeric(10,2) NOT NULL CHECK (recargo >= 0),
    total                   numeric(10,2) NOT NULL CHECK (total >= 0),

    estado                  text NOT NULL DEFAULT 'pendiente_pago'
        CHECK (estado IN (
            'pendiente_pago',
            'confirmada',
            'usada',
            'cancelada_cliente',
            'cancelada_funcion',
            'expirada'
        )),

    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_reserva_total
        CHECK (total = subtotal + recargo),
    CONSTRAINT chk_reserva_calculo_recargo
        CHECK (recargo = round(subtotal * porcentaje_recargo / 100, 2)),
    CONSTRAINT chk_reserva_vencimiento
        CHECK (fecha_expiracion > fecha_bloqueo),

    -- Necesaria para asegurar por FK que el detalle corresponde a la misma función.
    CONSTRAINT uq_reserva_id_funcion UNIQUE (id_reserva, id_funcion)
);

CREATE INDEX idx_reserva_usuario_fecha
    ON public.reserva (id_usuario, fecha_reserva DESC);

CREATE INDEX idx_reserva_funcion_estado
    ON public.reserva (id_funcion, estado);

CREATE INDEX idx_reserva_pendiente_expiracion
    ON public.reserva (fecha_expiracion)
    WHERE estado = 'pendiente_pago';

COMMENT ON TABLE public.reserva IS
'Compra/reserva. Una fila puede representar el checkout pendiente de pago durante 5 minutos y, después, la reserva confirmada o su estado final.';
COMMENT ON COLUMN public.reserva.id_usuario IS
'NULL para compra como invitado. Los datos del comprador se conservan en las columnas de snapshot.';
COMMENT ON COLUMN public.reserva.total IS
'Debe calcularlo el servidor a partir de los precios y el recargo válidos; el CHECK comprueba total = subtotal + recargo.';
COMMENT ON COLUMN public.reserva.fecha_expiracion IS
'Vencimiento del bloqueo temporal. Una operación segura debe comprobar el vencimiento en el servidor antes de aprobar el pago.';


-- 2. DETALLE_RESERVA: un asiento por fila, con precio/tipo congelados en la compra.
CREATE TABLE public.detalle_reserva (
    id_detalle              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva              bigint NOT NULL,
    id_funcion              bigint NOT NULL,
    id_asiento              bigint NOT NULL
        REFERENCES public.asiento(id) ON DELETE RESTRICT,

    tipo_entrada            text NOT NULL
        CHECK (tipo_entrada IN ('adulto', 'nino', 'tercera_edad')),
    precio_unitario         numeric(10,2) NOT NULL
        CHECK (precio_unitario >= 0),

    -- bloqueado: checkout pendiente; reservado: compra confirmada; liberado: ya no ocupa el asiento.
    estado                  text NOT NULL DEFAULT 'bloqueado'
        CHECK (estado IN ('bloqueado', 'reservado', 'liberado')),
    created_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_detalle_reserva_funcion
        FOREIGN KEY (id_reserva, id_funcion)
        REFERENCES public.reserva (id_reserva, id_funcion)
        ON DELETE RESTRICT,
    CONSTRAINT uq_detalle_reserva_asiento
        UNIQUE (id_reserva, id_asiento)
);

CREATE INDEX idx_detalle_reserva_reserva
    ON public.detalle_reserva (id_reserva);

-- Impide que dos reservas retengan/vendan el mismo asiento para la misma función.
-- Los detalles vencidos/cancelados deben cambiar a 'liberado' dentro de una operación
-- transaccional antes de volver a asignar el asiento.
CREATE UNIQUE INDEX uq_detalle_funcion_asiento_activo
    ON public.detalle_reserva (id_funcion, id_asiento)
    WHERE estado IN ('bloqueado', 'reservado');

COMMENT ON COLUMN public.detalle_reserva.id_funcion IS
'Repite la función de la reserva deliberadamente para imponer una restricción única por función/asiento; una FK compuesta evita que no coincida con RESERVA.';
COMMENT ON COLUMN public.detalle_reserva.estado IS
'Las operaciones de expiración y cancelación liberan el asiento actualizando este estado a liberado. No basta con dejar pasar la fecha de expiración.';


-- 3. PAGO: un registro por intento. Una reserva puede tener intentos rechazados y luego uno aprobado.
CREATE TABLE public.pago (
    id_pago                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva              bigint NOT NULL
        REFERENCES public.reserva(id_reserva) ON DELETE RESTRICT,
    monto                   numeric(10,2) NOT NULL CHECK (monto > 0),
    metodo_pago             text NOT NULL
        CHECK (metodo_pago IN ('tarjeta_credito', 'tarjeta_debito')),
    estado                  text NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'aprobado', 'rechazado', 'cancelado', 'expirado')),

    -- Clave generada por el backend y reutilizada ante reintentos HTTP de la misma solicitud.
    clave_idempotencia      uuid NOT NULL UNIQUE,
    ultimos_4_tarjeta       varchar(4) NULL
        CHECK (ultimos_4_tarjeta IS NULL OR ultimos_4_tarjeta ~ '^[0-9]{4}$'),

    fecha_intento           timestamptz NOT NULL DEFAULT now(),
    fecha_resultado         timestamptz NULL,
    fecha_pago              timestamptz NULL,
    detalle_resultado       text NULL,

    CONSTRAINT chk_pago_fechas_estado CHECK (
        (estado = 'pendiente' AND fecha_resultado IS NULL AND fecha_pago IS NULL)
        OR
        (estado = 'aprobado' AND fecha_resultado IS NOT NULL AND fecha_pago IS NOT NULL)
        OR
        (estado IN ('rechazado', 'cancelado', 'expirado')
            AND fecha_resultado IS NOT NULL AND fecha_pago IS NULL)
    )
);

CREATE INDEX idx_pago_reserva_fecha
    ON public.pago (id_reserva, fecha_intento DESC);

-- Como máximo un intento aprobado por reserva; los rechazos/reintentos sí se conservan.
CREATE UNIQUE INDEX uq_pago_reserva_aprobado
    ON public.pago (id_reserva)
    WHERE estado = 'aprobado';

COMMENT ON TABLE public.pago IS
'Historial de intentos de pago. No almacenar nunca el número completo de tarjeta ni el CVV.';
COMMENT ON COLUMN public.pago.clave_idempotencia IS
'El backend debe reutilizar la misma clave ante reintentos de la misma solicitud para evitar duplicados.';
COMMENT ON COLUMN public.pago.monto IS
'El backend debe comprobar que el monto coincide con el total de la reserva antes de confirmar el pago.';


-- 4. BOLETO: un QR por reserva según la decisión actual del proyecto.
CREATE TABLE public.boleto (
    id_boleto               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva              bigint NOT NULL UNIQUE
        REFERENCES public.reserva(id_reserva) ON DELETE RESTRICT,
    codigo_qr               uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    ruta_pdf                text NULL,
    fecha_generacion        timestamptz NOT NULL DEFAULT now(),
    fecha_uso               timestamptz NULL,

    CONSTRAINT chk_boleto_ruta_pdf
        CHECK (ruta_pdf IS NULL OR length(btrim(ruta_pdf)) > 0)
);

COMMENT ON TABLE public.boleto IS
'Un boleto/QR por reserva. fecha_uso NULL significa que todavía no se ha validado; no hace falta duplicar este dato con un booleano utilizado.';
COMMENT ON COLUMN public.boleto.codigo_qr IS
'Token opaco y no secuencial; no incluir datos personales en el QR.';
COMMENT ON COLUMN public.boleto.ruta_pdf IS
'Guardar la ruta/clave del objeto en almacenamiento privado, no una URL pública permanente.';


-- 5. PUNTO_LEALTAD: historial de movimientos, no un saldo sobrescrito.
CREATE TABLE public.punto_lealtad (
    id_movimiento            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario               uuid NOT NULL
        REFERENCES public.usuarios(id_usuario) ON DELETE RESTRICT,
    id_reserva               bigint NOT NULL
        REFERENCES public.reserva(id_reserva) ON DELETE RESTRICT,
    tipo_movimiento          text NOT NULL
        CHECK (tipo_movimiento IN (
            'compra',
            'reversion_compra',
            'reembolso_cancelacion'
        )),
    puntos                   integer NOT NULL CHECK (puntos <> 0),
    fecha_movimiento         timestamptz NOT NULL DEFAULT now(),
    descripcion              text NULL,

    CONSTRAINT chk_puntos_signo CHECK (
        (tipo_movimiento = 'reversion_compra' AND puntos < 0)
        OR
        (tipo_movimiento IN ('compra', 'reembolso_cancelacion') AND puntos > 0)
    ),
    CONSTRAINT uq_punto_reserva_tipo UNIQUE (id_reserva, tipo_movimiento)
);

CREATE INDEX idx_punto_lealtad_usuario_fecha
    ON public.punto_lealtad (id_usuario, fecha_movimiento DESC);

COMMENT ON TABLE public.punto_lealtad IS
'Libro de movimientos: compra suma puntos, reversion_compra los resta y reembolso_cancelacion acredita los puntos de devolución. Invitados no generan puntos.';
COMMENT ON COLUMN public.punto_lealtad.puntos IS
'Guardar valores positivos para acreditaciones y negativos para reversiones. El backend debe impedir movimientos duplicados y validar la propiedad de la reserva.';


-- Seguridad: RLS activado en todas las tablas nuevas.
-- Las escrituras no se conceden directamente al navegador; deben hacerse desde backend/RPC autorizada.
ALTER TABLE public.reserva ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalle_reserva ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pago ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.boleto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.punto_lealtad ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE
    public.reserva,
    public.detalle_reserva,
    public.pago,
    public.boleto,
    public.punto_lealtad
FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE
    public.reserva,
    public.detalle_reserva,
    public.pago,
    public.boleto,
    public.punto_lealtad
TO authenticated;

GRANT ALL PRIVILEGES ON TABLE
    public.reserva,
    public.detalle_reserva,
    public.pago,
    public.boleto,
    public.punto_lealtad
TO service_role;

-- Conceder privilegios a las secuencias de identidad de estas cinco tablas a service_role.
DO $$
DECLARE
    v_table text;
    v_column text;
    v_sequence text;
BEGIN
    FOR v_table, v_column IN
        SELECT * FROM (VALUES
            ('reserva', 'id_reserva'),
            ('detalle_reserva', 'id_detalle'),
            ('pago', 'id_pago'),
            ('boleto', 'id_boleto'),
            ('punto_lealtad', 'id_movimiento')
        ) AS seqs(table_name, column_name)
    LOOP
        v_sequence := pg_get_serial_sequence(format('%I.%I', 'public', v_table), v_column);
        IF v_sequence IS NOT NULL THEN
            EXECUTE format(
                'GRANT USAGE, SELECT, UPDATE ON SEQUENCE %s TO service_role',
                v_sequence
            );
        END IF;
    END LOOP;
END $$;

-- Los clientes autenticados solo pueden leer sus propios registros.
-- Los invitados acceden a su compra a través de rutas de backend autorizadas.
CREATE POLICY reserva_select_propia
    ON public.reserva FOR SELECT TO authenticated
    USING (id_usuario = (SELECT auth.uid()));

CREATE POLICY detalle_reserva_select_propio
    ON public.detalle_reserva FOR SELECT TO authenticated
    USING (EXISTS (
        SELECT 1
        FROM public.reserva r
        WHERE r.id_reserva = detalle_reserva.id_reserva
          AND r.id_usuario = (SELECT auth.uid())
    ));

CREATE POLICY pago_select_propio
    ON public.pago FOR SELECT TO authenticated
    USING (EXISTS (
        SELECT 1
        FROM public.reserva r
        WHERE r.id_reserva = pago.id_reserva
          AND r.id_usuario = (SELECT auth.uid())
    ));

CREATE POLICY boleto_select_propio
    ON public.boleto FOR SELECT TO authenticated
    USING (EXISTS (
        SELECT 1
        FROM public.reserva r
        WHERE r.id_reserva = boleto.id_reserva
          AND r.id_usuario = (SELECT auth.uid())
    ));

CREATE POLICY punto_lealtad_select_propio
    ON public.punto_lealtad FOR SELECT TO authenticated
    USING (id_usuario = (SELECT auth.uid()));

COMMIT;

