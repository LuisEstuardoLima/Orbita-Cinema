-- 7) Privilegios (idempotentes). El flujo de compra usa EXCLUSIVAMENTE la
--    service role (Server Actions y funciones SQL), igual que el resto del
--    flujo de bloqueo: anon no tiene acceso y authenticated solo lee el
--    detalle (ocupación de asientos), como documenta lib/db/asientos.ts.
--    RLS se queda como esté en cada entorno; si se decide activarlo, hay
--    que añadir las políticas correspondientes junto con esto.
revoke all on public.reserva, public.detalle_reserva, public.pago, public.boleto
  from anon;
grant select on public.detalle_reserva to authenticated;
grant all on public.reserva, public.detalle_reserva, public.pago, public.boleto
  to service_role;
