-- 1) reserva: la compra completa. Una fila nace como checkout pendiente
--    (estado 'pendiente_pago' con bloqueo de 5 minutos; ver SCRUM-119) y
--    termina 'confirmada' cuando el pago se registra, o en un estado final
--    ('expirada', 'cancelada_cliente'). El comprador se guarda en columnas
--    snapshot (nombre/correo/teléfono) para que la reserva sea legible
--    aunque la cuenta o el enlace de invitado ya no existan.
create table if not exists public.reserva (
  id_reserva          bigint generated by default as identity primary key,
  -- NULL = compra como invitado. ON DELETE SET NULL conserva la reserva si
  -- baja la cuenta: el snapshot nombre/correo ya vive en la propia fila.
  id_usuario          uuid references public.usuarios (id_usuario) on delete set null,
  id_funcion          bigint not null references public.funcion (id),
  nombre_comprador    text   not null,
  correo_comprador    text   not null,
  telefono_comprador  text,
  fecha_reserva       timestamptz not null default now(),
  fecha_bloqueo       timestamptz not null default now(),
  -- Vencimiento del bloqueo temporal (SCRUM-119). Una operación segura
  -- debe comprobar el vencimiento en el servidor antes de aprobar el pago.
  fecha_expiracion    timestamptz not null default (now() + interval '5 minutes'),
  -- El backend recalcula todos los montos; nunca confiar en los de la URL.
  subtotal            numeric(10,2) not null,
  porcentaje_recargo  numeric(5,2)  not null default 5.0,
  monto_recargo       numeric(10,2) not null,
  total               numeric(10,2) not null,
  estado              text not null default 'pendiente_pago',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  -- SCRUM-119: dueño del bloqueo temporal (cookie httpOnly del navegador).
  token_sesion        uuid,
  constraint reserva_estado_check
    check (estado in ('pendiente_pago', 'confirmada', 'expirada', 'cancelada_cliente')),
  constraint chk_reserva_total
    check (total = subtotal + monto_recargo),
  constraint chk_reserva_calculo_recargo
    check (monto_recargo = round(subtotal * porcentaje_recargo / 100, 2)),
  -- Ancla de la FK compuesta de detalle_reserva (id_reserva, id_funcion).
  constraint uq_reserva_id_funcion unique (id_reserva, id_funcion)
);

-- 2) detalle_reserva: una fila por asiento de la reserva. 'bloqueado' es el
--    estado temporal del SCRUM-119; al confirmar el pago pasa a 'reservado'
--    y al liberarse/cancelarse a 'liberado' (no basta con que venza la
--    fecha: hay que actualizar el estado).
create table if not exists public.detalle_reserva (
  id_detalle    bigint generated by default as identity primary key,
  id_reserva    bigint not null,
  -- Repite la función de la reserva deliberadamente: junto con id_reserva
  -- forma la FK compuesta que impide que un detalle no cuente con la misma
  -- función que su reserva.
  id_funcion    bigint not null,
  id_asiento    bigint not null references public.asiento (id),
  tipo_entrada  text   not null,
  precio        numeric(10,2) not null,
  estado        text   not null default 'bloqueado',
  created_at    timestamptz not null default now(),
  constraint detalle_reserva_tipo_entrada_check
    check (tipo_entrada in ('adulto', 'tercera_edad', 'nino')),
  constraint detalle_reserva_precio_unitario_check
    check (precio >= 0),
  constraint detalle_reserva_estado_check
    check (estado in ('bloqueado', 'reservado', 'liberado')),
  constraint fk_detalle_reserva_funcion
    foreign key (id_reserva, id_funcion)
    references public.reserva (id_reserva, id_funcion)
);

-- 3) pago: historial de intentos de pago (uno por fila). NUNCA se guarda el
--    número completo de tarjeta ni el CVV; solo los últimos 4 dígitos.
--    'clave_idempotencia' es el ancla anti-duplicados: el backend reutiliza
--    la misma clave al reintentar la misma solicitud.
create table if not exists public.pago (
  id_pago            bigint generated by default as identity primary key,
  id_reserva         bigint not null references public.reserva (id_reserva),
  monto              numeric(10,2) not null,
  metodo_pago        text not null,
  estado             text not null default 'pendiente',
  clave_idempotencia uuid not null,
  ultimos_4_tarjeta  varchar(4),
  fecha_intento      timestamptz not null default now(),
  fecha_resultado    timestamptz,
  detalle_resultado  text,
  constraint pago_monto_check
    check (monto > 0),
  constraint pago_metodo_pago_check
    check (metodo_pago in ('tarjeta_credito', 'tarjeta_debito')),
  constraint pago_estado_check
    check (estado in ('pendiente', 'aprobado', 'rechazado')),
  constraint pago_ultimos_4_tarjeta_check
    check (ultimos_4_tarjeta is null or ultimos_4_tarjeta ~ '^[0-9]{4}$'),
  constraint pago_clave_idempotencia_key unique (clave_idempotencia)
);

-- 4) boleto: un boleto/QR por reserva. 'codigo_qr' es un token opaco (uuid,
--    no secuencial) y 'ruta_pdf' guarda la clave del objeto en almacenamiento
--    privado, no una URL pública permanente. 'fecha_uso' NULL = sin validar.
create table if not exists public.boleto (
  id_boleto        bigint generated by default as identity primary key,
  id_reserva       bigint not null references public.reserva (id_reserva),
  codigo_qr        uuid not null default gen_random_uuid(),
  ruta_pdf         text,
  fecha_generacion timestamptz not null default now(),
  fecha_uso        timestamptz,
  constraint boleto_id_reserva_key unique (id_reserva),
  constraint boleto_codigo_qr_key unique (codigo_qr)
);

-- 5) Índices. Ambos ya los crea sprint3-bloqueo-asientos.sql con estos
--    mismos nombres (aquí quedan documentados y garantizados aunque ese
--    script todavía no se haya corrido en una BD nueva):
--      · único por función/asiento: es lo que impide vender dos veces el
--        mismo asiento en la misma función;
--      · parcial por token: acelera "¿sigue vigente el bloqueo?".
create unique index if not exists uq_detalle_reserva_asiento_funcion_activo
  on public.detalle_reserva (id_funcion, id_asiento)
  where estado in ('bloqueado', 'reservado');

create index if not exists idx_reserva_token_pendiente
  on public.reserva (token_sesion)
  where estado = 'pendiente_pago';

