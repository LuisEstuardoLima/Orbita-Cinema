-- Crea desde cero las tablas `rol` y `usuarios` + trigger de alta.
-- Es idempotente: se puede correr más de una vez sin duplicar nada.
--
-- FUENTE ÚNICA DEL ROL (RF-040): public.usuarios.id_rol -> public.rol.id_rol
-- Ni el JWT ni user_metadata deciden permisos: middleware y guards leen
-- la BD por request (más fresco que app_metadata y sin doble escritura).
-- =====================================================================

-- 1) Catálogo de roles (RF-040) ------------------------------------------
create table if not exists public.rol (
  id_rol integer generated by default as identity primary key,
  nombre text not null unique
);

alter table public.rol enable row level security;

-- Los nombres de rol no son datos sensibles (se muestran en la UI);
-- se habilita RLS y se permite solo la lectura, para que nadie
-- inserte, edite o borre roles desde el navegador.
drop policy if exists "Cualquiera puede leer los roles" on public.rol;
create policy "Cualquiera puede leer los roles"
  on public.rol for select using (true);
-- Sin políticas de INSERT/UPDATE/DELETE: solo el service role los modifica.

insert into public.rol (id_rol, nombre) values
  (1, 'Cliente'),
  (2, 'Colaborador'),
  (3, 'Administrador')
on conflict do nothing;

-- 2) Usuarios (PK = id_usuario, FK a auth.users.id; el rol vive en id_rol) -
create table if not exists public.usuarios (
  id_usuario uuid primary key references auth.users(id) on delete cascade,
  nombre     text not null,
  apellido   text not null,
  telefono   text,
  id_rol     integer not null references public.rol(id_rol),
  created_at timestamp with time zone not null default timezone('utc', now())
);

-- 3) Seguridad por nivel de fila ----------------------------------------
alter table public.usuarios enable row level security;

drop policy if exists "El usuario puede ver su propio usuario" on public.usuarios;
create policy "El usuario puede ver su propio usuario"
  on public.usuarios for select
  using (auth.uid() = id_usuario);

drop policy if exists "El usuario puede actualizar su propio usuario" on public.usuarios;
create policy "El usuario puede actualizar su propio usuario"
  on public.usuarios for update
  using (auth.uid() = id_usuario)
  with check (auth.uid() = id_usuario);
-- Sin política de INSERT (el alta es el trigger) ni de DELETE (la baja es lógica/admin).

-- 3b) PRIVILEGIOS DE COLUMNA: sin esto, el usuario podría hacer
--     `update usuarios set id_rol = 3 where id_usuario = auth.uid()`
--     y auto-promoverse a Administrador (RLS permite la fila; los grants
--     impiden escribir la columna id_rol).
revoke update, insert, delete, truncate on public.usuarios from anon, authenticated;
grant update (nombre, apellido, telefono) on public.usuarios to authenticated;

-- 4) Trigger de alta de usuario (idempotente y endurecido) --------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id_rol integer;
begin
  select id_rol into v_id_rol from public.rol where nombre = 'Cliente';
  if v_id_rol is null then
    raise exception 'No existe el rol "Cliente" en public.rol';
  end if;

  insert into public.usuarios (id_usuario, nombre, apellido, telefono, id_rol)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nombre', ''),
    coalesce(new.raw_user_meta_data->>'apellido', ''),
    new.raw_user_meta_data->>'telefono',
    v_id_rol  -- nunca desde metadata: evita el autoascenso de rol
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 5) Backfill: usuarios de prueba registrados ANTES de correr este script --
-- (el trigger no se dispara retroactivamente; si no hay usuarios, no hace nada)
insert into public.usuarios (id_usuario, nombre, apellido, telefono, id_rol)
select u.id,
       coalesce(u.raw_user_meta_data->>'nombre', ''),
       coalesce(u.raw_user_meta_data->>'apellido', ''),
       u.raw_user_meta_data->>'telefono',
       coalesce((select id_rol from public.rol where nombre = 'Cliente'), 1)
from auth.users u
on conflict (id_usuario) do nothing;

